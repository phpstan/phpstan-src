<?php declare(strict_types = 1);

namespace PHPStan\Build;

use function fclose;
use function is_resource;
use function preg_match;
use function proc_close;
use function proc_open;
use function sprintf;
use function stream_get_contents;
use function substr;
use function trim;
use function var_export;

/**
 * The phpstan_turbo version this checkout of PHPStan expects: the short SHA
 * of the last commit touching turbo-ext/src — the same computation the
 * extension's Makefile bakes into the binary, so a binary built from this
 * checkout matches by construction. build/generate-turbo-manifest.php writes
 * it into vendor/turbo-extension-version.php on every autoloader dump (the
 * phar carries that file too); build/turbo-extension-version.php prints it
 * for the workflows.
 */
final class TurboExtensionVersion
{

	/**
	 * Null without a usable git checkout — the enabler then expects nothing,
	 * and the extension stays inactive.
	 */
	public static function resolve(string $root): ?string
	{
		// an argument list rather than a command line: no shell, so no
		// quoting and no /dev/null that would not exist on Windows
		$process = proc_open(
			['git', '-C', $root, 'log', '-1', '--format=%H', '--', 'turbo-ext/src'],
			[1 => ['pipe', 'w'], 2 => ['pipe', 'w']],
			$pipes,
		);
		if (!is_resource($process)) {
			return null;
		}

		$output = stream_get_contents($pipes[1]);
		fclose($pipes[1]);
		fclose($pipes[2]);
		if (proc_close($process) !== 0 || $output === false) {
			return null;
		}

		$sha = trim($output);
		if (preg_match('~^[0-9a-f]{40,}$~', $sha) !== 1) {
			return null;
		}

		return substr($sha, 0, 7);
	}

	public static function render(?string $version): string
	{
		return sprintf(
			<<<'PHP'
<?php declare(strict_types = 1);

// turbo-extension-version.php @generated by build/generate-turbo-manifest.php
// — do not edit. The phpstan_turbo version PHPStan\Turbo\TurboExtensionEnabler
// activates: the short SHA of the last commit touching turbo-ext/src (null
// without a git checkout to read it from).

return %s;

PHP,
			var_export($version, true),
		);
	}

}

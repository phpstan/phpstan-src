#!/usr/bin/env bash
# @tags result-cache

function set_up() {
	e2e::set_up
}

function tear_down() {
	e2e::tear_down
}

function test_bug_14932() {
	# https://github.com/phpstan/phpstan/issues/14932
	# An error deduplicated directly into the trait must behave deterministically:
	# the same report, the same ignore matching and the same generated baseline on
	# every run, independent of result-cache state (cold/warm/partial) and of
	# worker arrival order.
	cp AMailer.php.dist src/Mailers/AMailer.php
	# With no ignores: the deduplicated error is reported once, directly in the
	# trait file (no "in context of"); errors whose message differs per using
	# class stay reported in each class context.
	../../bin/phpstan clear-result-cache
	OUTPUT=$(../../bin/phpstan analyse --error-format=raw 2>&1) && CODE=0 || CODE=$?
	assert_same "1" "$CODE"
	assert_contains 'SomeTrait.php:17:Right side of && is always true.' "$OUTPUT"
	assert_not_contains 'SomeTrait.php (in context of' "$OUTPUT"
	assert_contains 'DiffMessageTrait.php (in context of class Bug14932\AMailer):10:Strict comparison' "$OUTPUT"
	assert_contains 'DiffMessageTrait.php (in context of class Bug14932\BMailer):10:Strict comparison' "$OUTPUT"
	# An ignoreErrors path targeting the trait file hides the error from all
	# using classes - with both an empty and a primed result cache.
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse --error-format=raw -c ignore-trait-path.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	../../bin/phpstan analyse --error-format=raw -c ignore-trait-path.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	# An ignoreErrors path targeting one using class accounts only for that
	# class's context: the entry matches (no ignore.unmatched), and the error is
	# still reported in the context of the other class - deterministically, with
	# both an empty and a primed result cache.
	../../bin/phpstan clear-result-cache
	OUTPUT=$(../../bin/phpstan analyse --error-format=raw -c ignore-class-a-path.neon 2>&1) && CODE=0 || CODE=$?
	assert_same "1" "$CODE"
	assert_contains 'SomeTrait.php (in context of class Bug14932\BMailer):17:Right side of && is always true.' "$OUTPUT"
	assert_not_contains 'was not matched' "$OUTPUT"
	OUTPUT=$(../../bin/phpstan analyse --error-format=raw -c ignore-class-a-path.neon 2>&1) && CODE=0 || CODE=$?
	assert_same "1" "$CODE"
	assert_contains 'SomeTrait.php (in context of class Bug14932\BMailer):17:Right side of && is always true.' "$OUTPUT"
	../../bin/phpstan clear-result-cache
	OUTPUT=$(../../bin/phpstan analyse --error-format=raw -c ignore-class-b-path.neon 2>&1) && CODE=0 || CODE=$?
	assert_same "1" "$CODE"
	assert_contains 'SomeTrait.php (in context of class Bug14932\AMailer):17:Right side of && is always true.' "$OUTPUT"
	assert_not_contains 'was not matched' "$OUTPUT"
	# Entries covering every using class hide the error completely - this is what
	# a baseline generated by PHPStan <= 2.1 recorded (one entry per class
	# context), so such baselines keep working with no unmatched entries.
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse --error-format=raw -c ignore-both-class-paths.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	../../bin/phpstan analyse --error-format=raw -c ignore-both-class-paths.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	# A directory path covering the using classes (but not the trait file) accounts
	# per-context too: without count it hides all contexts...
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse --error-format=raw -c ignore-dir-path.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	# ...and with count: 1 it covers one of the two contexts: the other is reported
	# in its context, and the count mismatch reports the true occurrence count.
	../../bin/phpstan clear-result-cache
	OUTPUT=$(../../bin/phpstan analyse --error-format=raw -c ignore-dir-count.neon 2>&1) && CODE=0 || CODE=$?
	assert_same "1" "$CODE"
	assert_contains 'SomeTrait.php (in context of class Bug14932\BMailer):17:Right side of && is always true.' "$OUTPUT"
	assert_contains 'is expected to occur 1 time, but occurred 2 times' "$OUTPUT"
	# The add-a-using-class flicker from the issue: prime the result cache with
	# BMailer as the trait's only user (the class-pathed entry covers the only
	# context), then add AMailer. The AMailer context is reported - on the
	# partial run and identically on every unchanged run after it.
	rm src/Mailers/AMailer.php
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse --error-format=raw -c ignore-class-b-path.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	cp AMailer.php.dist src/Mailers/AMailer.php
	OUTPUT=$(../../bin/phpstan analyse --error-format=raw -c ignore-class-b-path.neon 2>&1) && CODE=0 || CODE=$?
	assert_same "1" "$CODE"
	assert_contains 'SomeTrait.php (in context of class Bug14932\AMailer):17:Right side of && is always true.' "$OUTPUT"
	OUTPUT=$(../../bin/phpstan analyse --error-format=raw -c ignore-class-b-path.neon 2>&1) && CODE=0 || CODE=$?
	assert_same "1" "$CODE"
	assert_contains 'SomeTrait.php (in context of class Bug14932\AMailer):17:Right side of && is always true.' "$OUTPUT"
	# --generate-baseline attributes the fully deduplicated error to the trait
	# file, and the baseline holds on re-run with an empty and a primed cache.
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse -c generate-only.neon --generate-baseline=baseline.neon
	assert_contains 'path: src/SomeTrait.php' "$(cat baseline.neon)"
	assert_not_contains 'AMailer.php' "$(cat baseline.neon)"
	assert_not_contains 'BMailer.php' "$(cat baseline.neon)"
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse --error-format=raw -c with-baseline.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	../../bin/phpstan analyse --error-format=raw -c with-baseline.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	# Generating a baseline on top of a one-class ignore records the surviving
	# context under its class path, and the combination holds on re-run.
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse -c ignore-class-a-path.neon --generate-baseline=partial-baseline.neon
	assert_contains 'path: src/Mailers/BMailer.php' "$(cat partial-baseline.neon)"
	assert_not_contains 'SomeTrait.php' "$(cat partial-baseline.neon)"
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse --error-format=raw -c with-partial-baseline.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	../../bin/phpstan analyse --error-format=raw -c with-partial-baseline.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	# A full generated baseline (trait path for the deduplicated error, class
	# paths for the per-context errors) holds on re-run as well.
	../../bin/phpstan clear-result-cache
	../../bin/phpstan --generate-baseline=full-baseline.neon
	assert_contains 'path: src/Mailers/AMailer.php' "$(cat full-baseline.neon)"
	assert_contains 'path: src/Mailers/BMailer.php' "$(cat full-baseline.neon)"
	assert_contains 'path: src/SomeTrait.php' "$(cat full-baseline.neon)"
	../../bin/phpstan clear-result-cache
	../../bin/phpstan analyse --error-format=raw -c with-full-baseline.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
	../../bin/phpstan analyse --error-format=raw -c with-full-baseline.neon 2>&1 && CODE=0 || CODE=$?
	assert_same "0" "$CODE"
}

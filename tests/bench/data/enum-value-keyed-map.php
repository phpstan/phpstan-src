/**
 * Writing through a union offset gives the array 250 optional keys that all hold
 * the same 250-case value type. Every merge of two such shapes unioned that value
 * type once per key, and comparing two of them called getOffsetValueType() and
 * isSuperTypeOf() once per key as well.
 *
 * `bin/phpstan analyse -l 8 --debug` with bleeding edge on this file: 0.82 s on 2.3.x, 0.26 s with the fix.
 *
 * @param array<value-of<Code>, int> $counts
 */
function pick(array $counts): void
{
	$missing = [];
	foreach ($counts as $value => $count) {
		if ($count < 2) {
			$missing[$value] = Code::from($value);
		}
	}
}

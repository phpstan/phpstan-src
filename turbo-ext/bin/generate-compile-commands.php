<?php declare(strict_types = 1);

/**
 * Writes compile_commands.json — the compilation database clang-tidy reads
 * the compile flags from (make lint-turbo).
 *
 * The build is a plain Makefile, so nothing produces the database as a side
 * effect of building (bear/compiledb are not part of the toolchain here).
 * The flags below therefore mirror the Makefile's CXXFLAGS; when that
 * changes, this changes with it. The generated sources are left out for the
 * same reason the Makefile leaves them out of the lint file list: a finding
 * in them can only be fixed in their generator.
 *
 * The version define is a placeholder rather than the real short SHA, which
 * would rewrite the database on every commit and invalidate nothing but
 * itself.
 */

$root = dirname(__DIR__);

$phpConfig = getenv('PHP_CONFIG');
if ($phpConfig === false || $phpConfig === '') {
	$phpConfig = 'php-config';
}

$includes = shell_exec(escapeshellcmd($phpConfig) . ' --includes 2>/dev/null');
if (!is_string($includes) || trim($includes) === '') {
	fwrite(STDERR, sprintf("%s --includes produced nothing — is the PHP development package installed?\n", $phpConfig));
	exit(1);
}
$includes = trim($includes);

$flags = [
	'-std=c++17',
	'-O2',
	'-fPIC',
	// compiler warnings are the build's job — it compiles with -Werror, and
	// the engine's headers warn in bulk when they are not compiled the way
	// the build compiles them; clang-tidy only has to parse
	'-w',
	'-DZEND_ENABLE_STATIC_TSRMLS_CACHE=1',
	// the escaped quotes survive both the JSON string and clang-tidy's
	// command-line splitting, so the macro expands to a string literal the
	// way the Makefile's -D does; without them main.cpp is handed the bare
	// identifier `lint` and fails to parse
	'-DPHPSTANTURBO_VERSION=\\"lint\\"',
	$includes,
];

// Homebrew's clang does not find the macOS SDK headers on its own, and the
// engine headers pull in system ones.
if (PHP_OS_FAMILY === 'Darwin') {
	$sdk = shell_exec('xcrun --show-sdk-path 2>/dev/null');
	if (is_string($sdk) && trim($sdk) !== '') {
		$flags[] = '-isysroot ' . trim($sdk);
	}
}

$sources = array_merge(
	glob($root . '/src/*.cpp') ?: [],
	glob($root . '/src/parser/*.cpp') ?: [],
);
sort($sources);

$database = [];
foreach ($sources as $source) {
	$relative = substr($source, strlen($root) + 1);
	// generated by bin/generate-parser-actions.php, never hand-edited
	if (preg_match('~^src/parser/ParserRunnerActions\d+\.cpp$~', $relative) === 1) {
		continue;
	}

	$database[] = [
		'directory' => $root,
		'file' => $relative,
		'command' => sprintf('c++ %s -c -o %s.o %s', implode(' ', $flags), substr($relative, 0, -4), $relative),
	];
}

$json = json_encode($database, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
file_put_contents($root . '/compile_commands.json', $json . "\n");

printf("compile_commands.json: %d sources\n", count($database));
